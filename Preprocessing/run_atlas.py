#!/usr/bin/env python3
"""Run and combine the SWED-calibrated missingness simulation atlas.

Each scenario is generated by ``simulate_swed.py`` and analysed by
``run_analysis.py`` with the same conditioning used for the real SWED fit
(at least one observed vital).  The combined outputs compare outcome-coefficient
recovery, selection-model g_x recovery, imputation bias, and convergence.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd

import simulate_swed as swed

HERE = Path(__file__).resolve().parent
SCENARIOS = swed.SCENARIOS


def _run_scenario(scenario: str, sim_dir: Path, res_dir: Path, n: int, seed: int,
                  iters: int, burn: int, chains: int, sensitivity: bool) -> None:
    observed, full, truth = swed.simulate(n, scenario, seed)
    swed.write(sim_dir, observed, full, truth)
    cmd = [
        sys.executable, str(HERE / "run_analysis.py"),
        "--data-dir", str(sim_dir),
        "--out-dir", str(res_dir),
        "--iter", str(iters),
        "--burn", str(burn),
        "--chains", str(chains),
        "--condition-any-vital",
    ]
    if not sensitivity:
        cmd.append("--skip-sensitivity")
    print("\n$", " ".join(cmd), flush=True)
    subprocess.run(cmd, cwd=HERE, check=True)


def _combine(out: Path, scenarios: list[str]) -> None:
    metric_rows, gx_rows, imp_rows, conv_rows = [], [], [], []
    for sc in scenarios:
        res = out / "results" / sc
        sim = out / "sim" / sc
        if not (res / "metrics.csv").exists():
            print(f"skip {sc}: no results", flush=True)
            continue
        observed = pd.read_csv(sim / "synthetic_ehr.csv")
        n_used = int(observed[swed.NAMES].notna().any(axis=1).sum())
        mt = pd.read_csv(res / "metrics.csv", index_col=0)
        mt.insert(0, "scenario", sc)
        mt.insert(1, "n", n_used)
        metric_rows.append(mt.reset_index().rename(columns={"index": "method"}))

        gx = pd.read_csv(res / "missingness_model.csv")
        gx["scenario"] = sc
        gx["n"] = n_used
        gx["bias"] = gx["gx_mean"] - gx["true_gx"]
        gx["covered"] = (gx["gx_lo"] <= gx["true_gx"]) & (gx["true_gx"] <= gx["gx_hi"])
        gx_rows.append(gx)

        imp = pd.read_csv(res / "imputation_check.csv")
        imp["scenario"] = sc
        imp["n"] = n_used
        imp_rows.append(imp)

        dg = pd.read_csv(res / "convergence_beta.csv", index_col=0)
        rcols = [c for c in dg.columns if c.endswith("rhat")]
        ecols = [c for c in dg.columns if c.endswith("ess")]
        row = {"scenario": sc, "n": n_used}
        for prefix in ("MAR", "MNAR"):
            rc = [c for c in rcols if c.startswith(prefix + "_")]
            ec = [c for c in ecols if c.startswith(prefix + "_")]
            row[f"{prefix}_max_rhat"] = float(dg[rc].max().max()) if rc else np.nan
            row[f"{prefix}_min_ess"] = float(dg[ec].min().min()) if ec else np.nan
        row["converged"] = bool(
            np.isfinite(row["MNAR_max_rhat"]) and row["MNAR_max_rhat"] < 1.10
            and np.isfinite(row["MNAR_min_ess"]) and row["MNAR_min_ess"] >= 50
        )
        conv_rows.append(row)

    if not metric_rows:
        return
    metrics = pd.concat(metric_rows, ignore_index=True)
    gx = pd.concat(gx_rows, ignore_index=True)
    imp = pd.concat(imp_rows, ignore_index=True)
    conv = pd.DataFrame(conv_rows)
    metrics.to_csv(out / "atlas_metrics.csv", index=False)
    gx.to_csv(out / "atlas_gx_recovery.csv", index=False)
    imp.to_csv(out / "atlas_imputation_shift.csv", index=False)
    conv.to_csv(out / "atlas_convergence.csv", index=False)

    gx_summary = (
        gx.groupby("scenario")
        .agg(gx_rmse=("bias", lambda x: float(np.sqrt(np.mean(x ** 2)))),
             gx_coverage=("covered", "mean"),
             gx_max_rhat=("gx_rhat", "max"),
             n=("n", "first"))
        .reset_index()
    )
    imp_summary = []
    for sc, sub in imp.groupby("scenario"):
        imp_summary.append({
            "scenario": sc,
            "mar_rmse": float(np.sqrt(np.mean((sub["bayes_mar"] - sub["true_missing_mean"]) ** 2))),
            "mnar_rmse": float(np.sqrt(np.mean((sub["bayes_mnar"] - sub["true_missing_mean"]) ** 2))),
            "observed_rmse": float(np.sqrt(np.mean((sub["observed_mean"] - sub["true_missing_mean"]) ** 2))),
        })
    imp_summary = pd.DataFrame(imp_summary)
    summary = gx_summary.merge(conv, on=["scenario", "n"], how="left").merge(imp_summary, on="scenario", how="left")

    _plot_gx(gx, out / "atlas_gx_recovery.png")
    _write_summary(out, metrics, summary)


def _plot_gx(gx: pd.DataFrame, path: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    scenarios = list(dict.fromkeys(gx["scenario"]))
    fig, axes = plt.subplots(1, len(scenarios), figsize=(3.2 * len(scenarios), 3.4), sharex=True, sharey=True)
    axes = np.atleast_1d(axes)
    lo = min(gx["true_gx"].min(), gx["gx_lo"].min()) - 0.2
    hi = max(gx["true_gx"].max(), gx["gx_hi"].max()) + 0.2
    for ax, sc in zip(axes, scenarios):
        sub = gx[gx["scenario"] == sc]
        ax.errorbar(sub["true_gx"], sub["gx_mean"],
                    yerr=np.vstack([sub["gx_mean"] - sub["gx_lo"], sub["gx_hi"] - sub["gx_mean"]]),
                    fmt="o", color="#eb6834", ecolor="#b0b0b0", capsize=2, ms=5)
        ax.plot([lo, hi], [lo, hi], "k--", lw=1)
        ax.axhline(0, color="grey", lw=0.8, ls=":")
        ax.axvline(0, color="grey", lw=0.8, ls=":")
        ax.set_title(sc, fontsize=9)
        ax.set_xlim(lo, hi)
        ax.set_ylim(lo, hi)
        ax.set_xlabel("true g_x")
    axes[0].set_ylabel("estimated g_x")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def _write_summary(out: Path, metrics: pd.DataFrame, summary: pd.DataFrame) -> None:
    write = metrics[metrics["method"].isin(["Oracle (complete data)", "Complete-case", "MICE", "Bayes, MAR", "Bayes, MNAR selection"])]
    pivot = write.pivot_table(index="method", columns="scenario", values="RMSE_all")
    lines = [
        "# SWED missingness simulation atlas",
        "",
        "All scenarios are conditioned on at least one observed vital, matching the real SWED fit.",
        "",
        "## Outcome-coefficient RMSE (lower is better)",
        "",
        pivot.round(4).to_markdown(),
        "",
        "## Selection-model and imputation recovery",
        "",
        summary.round(3).to_markdown(index=False),
        "",
        "`gx_rmse` and `gx_coverage` are across vitals with a non-zero or fitted own-value effect.",
        "`mar_rmse`, `mnar_rmse`, and `observed_rmse` compare posterior/observed means with the true missing-value mean.",
        "Only interpret scenarios with `converged=True`.",
        "",
        "## Files",
        "",
        "- `atlas_metrics.csv`: outcome-coefficient metrics by scenario and method.",
        "- `atlas_gx_recovery.csv`: true vs estimated `g_x` with 95% intervals.",
        "- `atlas_imputation_shift.csv`: observed, MAR, and MNAR missing-value means.",
        "- `atlas_convergence.csv`: R-hat/ESS gates by scenario.",
        "- `atlas_gx_recovery.png`: visual `g_x` recovery.",
        "",
    ]
    (out / "summary.md").write_text("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=20_000)
    ap.add_argument("--seed", type=int, default=20261112)
    ap.add_argument("--scenarios", default=",".join(SCENARIOS))
    ap.add_argument("--iter", type=int, default=1200)
    ap.add_argument("--burn", type=int, default=500)
    ap.add_argument("--chains", type=int, default=2)
    ap.add_argument("--out", type=Path, default=HERE / "atlas_results")
    ap.add_argument("--skip-run", action="store_true")
    ap.add_argument("--sensitivity", action="store_true")
    a = ap.parse_args()
    scenarios = [s.strip() for s in a.scenarios.split(",") if s.strip()]
    a.out.mkdir(parents=True, exist_ok=True)
    if not a.skip_run:
        for sc in scenarios:
            _run_scenario(sc, a.out / "sim" / sc, a.out / "results" / sc, a.n, a.seed,
                          a.iter, a.burn, a.chains, a.sensitivity)
    _combine(a.out, scenarios)
    print("wrote", a.out)


if __name__ == "__main__":
    main()
